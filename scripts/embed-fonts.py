#!/usr/bin/env python3
"""Regenerate section 13 (Fonts) of theme.css from the files in fonts/.

Obsidian themes ship as a single theme.css, and Obsidian injects that file as
text, so relative font URLs cannot work. Fonts therefore live in theme.css as
base64 data URLs. This script keeps that section reproducible:

    1. Put .woff2 files into fonts/ and list them in fonts/fonts.json.
    2. Run: python3 scripts/embed-fonts.py
    3. Reload Obsidian (Cmd+R / Ctrl+R).

Everything from the "== 13 FONTS" header to the end of theme.css is replaced.
Only the Python standard library is used.
"""

import base64
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
THEME = ROOT / "theme.css"
FONTS = ROOT / "fonts"
MARKER = "/* == 13 FONTS"


def build_section(config: dict) -> str:
    credits = "\n".join(f"   {line}" for line in config["credits"])
    header = (
        "/* == 13 FONTS ==============================================================\n"
        "   Embedded fonts (T-10, R-6). Variable fonts, Latin subset only.\n"
        "   Generated by scripts/embed-fonts.py from fonts/. Do not edit by hand.\n"
        "\n"
        f"{credits}\n"
        "\n"
        "   All fonts are licensed under the SIL Open Font License, Version 1.1:\n"
        "   https://openfontlicense.org\n"
        "   ========================================================================== */\n"
    )
    faces = []
    for face in config["faces"]:
        data = (FONTS / face["file"]).read_bytes()
        if data[:4] != b"wOF2":
            sys.exit(f"{face['file']} is not a woff2 file")
        encoded = base64.b64encode(data).decode("ascii")
        faces.append(
            "@font-face {\n"
            f'    font-family: "{face["family"]}";\n'
            f"    font-style: {face['style']};\n"
            f"    font-weight: {face['weight']};\n"
            "    font-display: swap;\n"
            f'    src: url(data:font/woff2;base64,{encoded}) format("woff2");\n'
            f"    unicode-range: {config['unicodeRange']};\n"
            "}\n"
        )
    return header + "\n" + "\n".join(faces)


def main() -> None:
    config = json.loads((FONTS / "fonts.json").read_text(encoding="utf-8"))
    css = THEME.read_text(encoding="utf-8")
    start = css.find(MARKER)
    if start == -1:
        sys.exit(f'Section marker "{MARKER}" not found in theme.css')
    THEME.write_text(css[:start] + build_section(config), encoding="utf-8")
    size_kb = THEME.stat().st_size / 1024
    print(f"Embedded {len(config['faces'])} font faces, theme.css is now {size_kb:.0f} KB")


if __name__ == "__main__":
    main()
